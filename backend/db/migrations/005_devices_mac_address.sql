-- เพิ่มคอลัมน์ mac_address ให้ตาราง devices
--
-- schema.sql ประกาศคอลัมน์นี้ไว้ตั้งแต่ตอนเขียนใหม่ด้วย Node แต่ฐานข้อมูลที่ย้ายมาจากระบบ PHP เดิม
-- ไม่เคยถูกเพิ่มให้ ระบบที่ติดตั้งใหม่จาก schema.sql จึงมีคอลัมน์นี้ ส่วนระบบที่ย้ายมาไม่มี
--
-- ผลคือ /api/provision_register ตอบ 500 ทุกครั้งเพราะ query อ้างคอลัมน์ที่ไม่มีอยู่จริง
-- เครื่องใหม่จึงลงทะเบียนตัวเองไม่ได้เลย
--
-- UNIQUE บนคอลัมน์ที่ยอมให้เป็น NULL — MySQL ยอมให้มีหลายแถวที่เป็น NULL ได้
-- เครื่องเดิมที่ลงทะเบียนไว้ก่อนหน้านี้จึงอยู่ต่อได้โดยไม่ต้องเติมค่า

ALTER TABLE devices
    ADD COLUMN mac_address VARCHAR(17) NULL UNIQUE AFTER device_key;
