/**
 * เทียบเวอร์ชันแบบ semantic — คืนค่า > 0 เมื่อ a ใหม่กว่า b
 *
 * เดิมโค้ดตรวจว่าอัปเดตสำเร็จด้วยการเทียบ "ไม่เท่ากับ" ซึ่งผิด: ค่าที่ต่างกันไม่ได้แปลว่าใหม่กว่า
 * เจอกับตัวเองตอนทดสอบ — คำสั่งถูกปิดเป็นสำเร็จทั้งที่บอร์ดยังรันเวอร์ชันเดิม เพราะค่าที่เก็บไว้
 * ตอนสั่งบังเอิญเป็นคนละตัวกับที่บอร์ดรายงานกลับมา
 */
export function compareVersions(a: string, b: string): number {
  const pa = String(a || '').split('.').map((n) => parseInt(n, 10) || 0);
  const pb = String(b || '').split('.').map((n) => parseInt(n, 10) || 0);
  for (let i = 0; i < 3; i++) {
    if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) - (pb[i] || 0);
  }
  return 0;
}
